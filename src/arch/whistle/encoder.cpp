bool compute_mel(const float *              pcm,
                 int                        n_samples,
                 const std::vector<float> & fb,
                 int                        n_mels,
                 MelResult &                out,
                 int                        n_threads) {
    constexpr int n_fft = 512;
    constexpr int win   = 400;
    constexpr int hop   = 160;
    constexpr int n_bin = n_fft / 2 + 1;

    out = MelResult{};
    if (pcm == nullptr || n_samples <= 0 || static_cast<int>(fb.size()) != n_mels * n_bin) {
        return false;
    }
    const int n_frames = n_samples / hop;
    if (n_frames < 1) {
        return false;
    }

    // Symmetric Hann (torch periodic=False), forward-map Frontend row "Window".
    std::vector<double> window(win);
    for (int k = 0; k < win; ++k) {
        window[k] = 0.5 - 0.5 * std::cos(2.0 * kPi * k / (win - 1));
    }

    // Nonzero mel band [lo, hi) of every FFT bin: the triangular filterbank is
    // ~97% zeros, and skipping exact-zero terms leaves every sum unchanged.
    std::vector<int> band_lo(n_bin, 0), band_hi(n_bin, 0);
    for (int b = 0; b < n_bin; ++b) {
        const float * fbr = fb.data() + static_cast<size_t>(b) * n_mels;
        int           lo = n_mels, hi = 0;
        for (int m = 0; m < n_mels; ++m) {
            if (fbr[m] != 0.0f) {
                lo = std::min(lo, m);
                hi = m + 1;
            }
        }
        band_lo[b] = lo < hi ? lo : 0;
        band_hi[b] = lo < hi ? hi : 0;
    }

    // Frames are independent: split them across threads (identical results).
    static const FftPlan plan(n_fft);
    std::vector<double>  power(static_cast<size_t>(n_frames) * n_mels, 0.0);
    auto                 frames = [&](int t0, int t1) {
        std::vector<double> re(n_fft), im(n_fft), spec(n_bin);
        for (int t = t0; t < t1; ++t) {
            const int start = t * hop - win / 2;
            for (int k = 0; k < n_fft; ++k) {
                double v = 0.0;
                if (k < win) {
                    const int s = start + k;
                    if (s >= 0 && s < n_samples) {
                        v = static_cast<double>(pcm[s]) * window[k];
                    }
                }
                re[k] = v;
                im[k] = 0.0;
            }
            fft_split(plan, re.data(), im.data());
            for (int b = 0; b < n_bin; ++b) {
                spec[b] = re[b] * re[b] + im[b] * im[b];  // std::norm
            }
            double * row = power.data() + static_cast<size_t>(t) * n_mels;
            for (int b = 0; b < n_bin; ++b) {
                const float * fbr = fb.data() + static_cast<size_t>(b) * n_mels;
                const double  s   = spec[b];
                for (int m = band_lo[b]; m < band_hi[b]; ++m) {
                    row[m] += s * static_cast<double>(fbr[m]);
                }
            }
        }
    };
    const int nt       = std::max(1, std::min(n_threads, n_frames / 64));
    auto      parallel = [&](auto && fn) {  // fn(t0, t1) over frame ranges
        if (nt == 1) {
            fn(0, n_frames);
            return;
        }
        std::vector<std::thread> pool;
        const int                per = (n_frames + nt - 1) / nt;
        for (int i = 1; i < nt; ++i) {
            pool.emplace_back(fn, i * per, std::min(n_frames, (i + 1) * per));
        }
        fn(0, std::min(n_frames, per));
        for (std::thread & th : pool) {
            th.join();
        }
    };
    parallel(frames);

    // No-speech statistic over per-frame mel energy (dB).
    std::vector<double> energy(n_frames);
    double              pmax = 0.0;
    for (int t = 0; t < n_frames; ++t) {
        double s = 0.0;
        for (int m = 0; m < n_mels; ++m) {
            const double p = power[static_cast<size_t>(t) * n_mels + m];
            s += p;
            pmax = std::max(pmax, p);
        }
        energy[t] = 10.0 * std::log10(s + 1e-30);
    }
    out.energy_spread_db = percentile_linear(energy, 99.0) - percentile_linear(energy, 10.0);

    // Log floor relative to the clip maximum, then per-bin normalization.
    const double        floor_v = 1e-8 * pmax;
    std::vector<double> lm(power.size());
    parallel([&](int t0, int t1) {
        for (size_t i = static_cast<size_t>(t0) * n_mels; i < static_cast<size_t>(t1) * n_mels; ++i) {
            lm[i] = std::log(power[i] + floor_v + 1e-30);
        }
    });
    // Per-bin statistics, accumulated over frames in order for every bin at
    // once (the bin loop is the contiguous one).
    out.mel.assign(power.size(), 0.0f);
    std::vector<double> mean(n_mels, 0.0), var(n_mels, 0.0), inv(n_mels, 0.0);
    for (int t = 0; t < n_frames; ++t) {
        const double * r = lm.data() + static_cast<size_t>(t) * n_mels;
        for (int m = 0; m < n_mels; ++m) {
            mean[m] += r[m];
        }
    }
    for (int m = 0; m < n_mels; ++m) {
        mean[m] /= n_frames;
    }
    for (int t = 0; t < n_frames; ++t) {
        const double * r = lm.data() + static_cast<size_t>(t) * n_mels;
        for (int m = 0; m < n_mels; ++m) {
            const double dv = r[m] - mean[m];
            var[m] += dv * dv;
        }
    }
    for (int m = 0; m < n_mels; ++m) {
        const double sd = std::sqrt(var[m] / n_frames);
        inv[m]          = sd > 0.0 ? 1.0 / sd : 0.0;
    }
    for (int t = 0; t < n_frames; ++t) {
        const size_t i0 = static_cast<size_t>(t) * n_mels;
        for (int m = 0; m < n_mels; ++m) {
            out.mel[i0 + m] = static_cast<float>((lm[i0 + m] - mean[m]) * inv[m]);
        }
    }
    out.n_frames = n_frames;
    return true;
}

