// out = A^T (Z B) for Z = z viewed as [ba][bb] (row i, column j): the same
// Kronecker apply as kron_apply, out[k*bb + l] = sum_ij z[i*bb + j] a[i][k] b[j][l].
void kron_host(const float * z, const float * a, const float * b, int ba, int bb, float * tmp, float * out) {
    for (int i = 0; i < ba; ++i) {
        float * t = tmp + i * bb;
        for (int l = 0; l < bb; ++l) {
            t[l] = 0.0f;
        }
        for (int j = 0; j < bb; ++j) {
            const float   zij = z[i * bb + j];
            const float * br  = b + j * bb;
            for (int l = 0; l < bb; ++l) {
                t[l] += zij * br[l];
            }
        }
    }
    for (int k = 0; k < ba; ++k) {
        float * o = out + k * bb;
        for (int l = 0; l < bb; ++l) {
            o[l] = 0.0f;
        }
        for (int i = 0; i < ba; ++i) {
            const float   aik = a[i * ba + k];
            const float * t   = tmp + i * bb;
            for (int l = 0; l < bb; ++l) {
                o[l] += aik * t[l];
            }
        }
    }
}

// kron_host with compile-time factor sizes: the BB-wide accumulator rows stay
// in vector registers.
template <int BA, int BB> void kron_fixed(const float * z, const float * a, const float * b, float * tmp, float * out) {
    for (int i = 0; i < BA; ++i) {
        float acc[BB] = {};
        for (int j = 0; j < BB; ++j) {
            const float   zij = z[i * BB + j];
            const float * br  = b + j * BB;
            for (int l = 0; l < BB; ++l) {
                acc[l] += zij * br[l];
            }
        }
        std::memcpy(tmp + i * BB, acc, sizeof(acc));
    }
    for (int k = 0; k < BA; ++k) {
        float acc[BB] = {};
        for (int i = 0; i < BA; ++i) {
            const float   aik = a[i * BA + k];
            const float * t   = tmp + i * BB;
            for (int l = 0; l < BB; ++l) {
                acc[l] += aik * t[l];
            }
        }
        std::memcpy(out + k * BB, acc, sizeof(acc));
    }
}

void kron_dispatch(const float * z, const float * a, const float * b, int ba, int bb, float * tmp, float * out) {
    if (ba == 16 && bb == 32) {
        kron_fixed<16, 32>(z, a, b, tmp, out);
    } else {
        kron_host(z, a, b, ba, bb, tmp, out);
    }
}

// y[k] = v[k] / (1 + exp(-v[k])) over n values (SiLU), vectorized exp where available.
void silu_inplace(float * v, float * scratch, int n) {
#if defined(__APPLE__)
    for (int k = 0; k < n; ++k) {
        scratch[k] = -v[k];
    }
    vvexpf(scratch, scratch, &n);
    for (int k = 0; k < n; ++k) {
        v[k] = v[k] / (1.0f + scratch[k]);
    }
#else
    (void) scratch;
    for (int k = 0; k < n; ++k) {
        v[k] = v[k] / (1.0f + std::exp(-v[k]));
    }
#endif
}

// Fused CPU HadamardMLP over x [d, N]; tokens are split across threads.
// src: x [d, N], optional ZCRMSNorm weight [d] (the op then computes
// HadamardMLP(ZCRMS(x)), each token normalized as rms_cpu does).
void hmlp_cpu(ggml_tensor * dst, int ith, int nth, void * ud) {
    const HmlpHost &    h     = *static_cast<const HmlpHost *>(ud);
    const ggml_tensor * x     = dst->src[0];
    const float *       norm  = dst->src[1] != nullptr ? static_cast<const float *>(dst->src[1]->data) : nullptr;
    const int           d     = h.d;
    const int64_t       N     = x->ne[1];
    const int64_t       per   = (N + nth - 1) / nth;
    const int64_t       n0    = per * ith;
    const int64_t       n1    = std::min(N, n0 + per);
    // Scratch on the stack (this runs once per node per thread).
    constexpr int       kMaxD = 1024;
    alignas(32) float   stack_buf[5 * kMaxD];
    std::vector<float>  heap_buf;
    float *             buf = stack_buf;
    if (d > kMaxD) {
        heap_buf.resize(5 * static_cast<size_t>(d));
        buf = heap_buf.data();
    }
    float *z = buf, *y = buf + d, *tmp = buf + 2 * d, *cond = buf + 3 * d, *xnorm = buf + 4 * d;
    auto   input = [&](int64_t n) {
        const float * xr = reinterpret_cast<const float *>(static_cast<const char *>(x->data) + n * x->nb[1]);
        if (norm == nullptr) {
            return xr;
        }
        rms_row(xr, xnorm, norm, d);
        return static_cast<const float *>(xnorm);
    };
    for (int64_t n = n0; n < n1; ++n) {
        const float * xr   = input(n);
        float *       out  = reinterpret_cast<float *>(static_cast<char *>(dst->data) + n * dst->nb[1]);
        // cond = 1 + softmax(x @ cond_v) @ cond_u (loops ordered for contiguous access)
        float         c[8] = {};
        for (int k = 0; k < d; ++k) {
            const float   xk = xr[k];
            const float * cv = h.cond_v + k * 8;
            for (int r = 0; r < 8; ++r) {
                c[r] += cv[r] * xk;
            }
        }
        float mx = c[0];
        for (int r = 1; r < 8; ++r) {
            mx = std::max(mx, c[r]);
        }
        float sum = 0.0f;
        for (float & v : c) {
            v = std::exp(v - mx);
            sum += v;
        }
        for (float & v : c) {
            v /= sum;
        }
        for (int k = 0; k < d; ++k) {
            cond[k] = 1.0f;
        }
        for (int r = 0; r < 8; ++r) {
            const float * cu = h.cond_u + r * d;
            const float   cr = c[r];
            for (int k = 0; k < d; ++k) {
                cond[k] += cu[k] * cr;
            }
        }
        for (int k = 0; k < d; ++k) {
            z[k] = xr[k] * h.d1[k];
        }
        kron_dispatch(z, h.a[0], h.b[0], h.ba, h.bb, tmp, y);
        for (int k = 0; k < d; ++k) {
            z[k] = y[h.perm1[k]] * h.d2[k] * cond[k] + h.b2[k];
        }
        silu_inplace(z, tmp, d);
        kron_dispatch(z, h.a[1], h.b[1], h.ba, h.bb, tmp, y);
        for (int k = 0; k < d; ++k) {
            z[k] = y[h.perm2[k]] * h.d3[k];
        }
        kron_dispatch(z, h.a[2], h.b[2], h.ba, h.bb, tmp, y);
        for (int k = 0; k < d; ++k) {
            out[k] = y[k] * h.d4[k];
        }
    }
}

