constexpr double kPi            = 3.14159265358979323846;
constexpr float  kNormEps       = 1e-6f;
constexpr int    kSinkhornIters = 20;

// Radix-2 FFT plan for n (power of two): the bit-reversal swaps and every
// stage's twiddles, generated by the w *= wl recurrence each butterfly group
// used to run (so every twiddle value is the same as recomputing it).
struct FftPlan {
    int                              n = 0;
    std::vector<std::pair<int, int>> swaps;
    std::vector<double>              twr, twi;  // stage len: entries [len/2 - 1, len - 1)

    explicit FftPlan(int n_) : n(n_) {
        for (int i = 1, j = 0; i < n; ++i) {
            int bit = n >> 1;
            for (; j & bit; bit >>= 1) {
                j ^= bit;
            }
            j ^= bit;
            if (i < j) {
                swaps.emplace_back(i, j);
            }
        }
        for (int len = 2; len <= n; len <<= 1) {
            const double               ang = -2.0 * kPi / static_cast<double>(len);
            const std::complex<double> wl(std::cos(ang), std::sin(ang));
            std::complex<double>       w(1.0, 0.0);
            for (int k = 0; k < len / 2; ++k) {
                twr.push_back(w.real());
                twi.push_back(w.imag());
                w *= wl;
            }
        }
    }
};

// In-place iterative radix-2 FFT on split real / imaginary arrays. Each
// butterfly is the std::complex<double> arithmetic it replaces, spelled out
// (v = x * w as (xr wr - xi wi, xr wi + xi wr), then u + v and u - v), so the
// results are bit-identical; the split layout lets the k loop vectorize.
void fft_split(const FftPlan & p, double * re, double * im) {
    for (const auto & [i, j] : p.swaps) {
        std::swap(re[i], re[j]);
        std::swap(im[i], im[j]);
    }
    for (int len = 2; len <= p.n; len <<= 1) {
        const int      half = len / 2;
        const double * tr   = p.twr.data() + (half - 1);
        const double * ti   = p.twi.data() + (half - 1);
        for (int i = 0; i < p.n; i += len) {
            double * __restrict ar = re + i;
            double * __restrict ai = im + i;
            double * __restrict br = re + i + half;
            double * __restrict bi = im + i + half;
            for (int k = 0; k < half; ++k) {
                const double vr = br[k] * tr[k] - bi[k] * ti[k];
                const double vi = br[k] * ti[k] + bi[k] * tr[k];
                const double ur = ar[k], ui = ai[k];
                ar[k] = ur + vr;
                ai[k] = ui + vi;
                br[k] = ur - vr;
                bi[k] = ui - vi;
            }
        }
    }
}

// numpy.percentile(..., method="linear").
double percentile_linear(std::vector<double> v, double q) {
    if (v.empty()) {
        return 0.0;
    }
    std::sort(v.begin(), v.end());
    const double pos = q / 100.0 * static_cast<double>(v.size() - 1);
    const size_t lo  = static_cast<size_t>(std::floor(pos));
    const size_t hi  = std::min(lo + 1, v.size() - 1);
    const double fr  = pos - static_cast<double>(lo);
    return v[lo] + (v[hi] - v[lo]) * fr;
}

