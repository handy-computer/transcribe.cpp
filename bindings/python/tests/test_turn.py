def _noise(n: int, seed: int = 7) -> array.array:
    out = array.array("f")
    s = seed | 1
    for _ in range(n):
        s = (s * 1664525 + 1013904223) & 0xFFFFFFFF
        out.append(((s >> 8) & 0xFFFFFF) / 16777216.0 - 0.5)
    return out


def _stream(turn: t.TurnSession, pcm, chunk: int):
    """Feed *pcm* in *chunk*-sample pieces and flush, checking the frame
    bookkeeping; returns the concatenated (turn, speech) probabilities."""
    probs: list = []
    speech: list = []
    for pos in range(0, len(pcm), chunk):
        r = turn.stream_feed(pcm[pos:pos + chunk])
        assert (r.p, r.ended) == (0.0, False)
        assert r.first_frame == len(probs)
        assert r.speech_first_frame == len(speech)
        probs.extend(r.probs)
        speech.extend(r.speech_probs)
    r = turn.stream_flush()
    assert r.first_frame == len(probs) and r.speech_first_frame == len(speech)
    probs.extend(r.probs)
    speech.extend(r.speech_probs)
    return tuple(probs), tuple(speech)


class _AlwaysAbort:
    """Point a session's native abort callback at one that always aborts;
    restores the session's own trampoline on exit."""

    def __init__(self, session: t.TurnSession):
        self.s = session
        self.cb = t._ABORT_CFUNC(lambda _ud: True)

    def __enter__(self):
        t._lib.transcribe_turn_set_abort_callback(self.s._handle, self.cb, None)

    def __exit__(self, *exc):
        t._lib.transcribe_turn_set_abort_callback(
            self.s._handle, self.s._abort_trampoline, None)


# --- smart_turn (clip only) ---------------------------------------------------


def test_smart_turn_toy_run(smart_turn_toy_model_path):
    with t.Model(smart_turn_toy_model_path, backend="cpu") as model:
        assert model.roles == {t.Role.TURN}
        assert model.turn_info == t.TurnInfo(sample_rate=16000, max_audio_ms=200,
                                             frame_samples=0, has_speech=False,
                                             threshold=0.5)
        with pytest.raises(t.UnsupportedRole):
            model.vad_info
        with model.turn_session(n_threads=1) as turn:
            r = turn.run(_noise(5000))
            assert 0.0 <= r.p <= 1.0
            assert r.ended == (r.p >= 0.5)
            assert (r.probs, r.first_frame, r.speech_probs, r.speech_first_frame) == ((), 0, (), 0)

            # The threshold override decides `ended`; negative = model default.
            assert turn.run(_noise(5000), threshold=0.0).ended is True
            assert turn.run(_noise(5000), threshold=1.0).ended is (r.p >= 1.0)
            assert turn.run(_noise(5000), threshold=-1).ended == r.ended
            assert turn.run(_noise(5000), threshold=r.p).ended is True

            # Longer input is scored on its last max_audio_ms (3200 samples).
            long = _noise(9000, seed=3)
            assert turn.run(long).p == turn.run(long[-3200:]).p

            # A clip model cannot stream.
            with pytest.raises(t.NotImplementedByModel):
                turn.stream_feed(_noise(640))
            with pytest.raises(t.NotImplementedByModel):
                turn.stream_flush()
            with pytest.raises(t.NotImplementedByModel):
                t.TurnSession.stream_feed_batch([(turn, _noise(640))])
            turn.stream_reset()  # a no-op, never raises
            assert turn.timings.load_ms >= 0.0


