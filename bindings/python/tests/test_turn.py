# --- sava (streaming, speech track) ---------------------------------------------


def test_sava_toy_run_and_stream(sava_toy_model_path):
    pcm = _noise(16 * 640 + 100)  # 16 full frames + a padded tail
    with t.Model(sava_toy_model_path, backend="cpu") as model:
        assert model.roles == {t.Role.VAD, t.Role.TURN}
        assert model.turn_info == t.TurnInfo(sample_rate=16000, max_audio_ms=0,
                                             frame_samples=640, has_speech=True,
                                             threshold=pytest.approx(0.9))
        with model.turn_session(n_threads=1) as turn:
            r = turn.run(pcm)
            assert len(r.probs) == 17 and len(r.speech_probs) == 17
            assert (r.first_frame, r.speech_first_frame) == (0, 0)
            assert r.p == r.probs[-1]
            assert r.ended == (r.p >= model.turn_info.threshold)
            assert turn.run(pcm, threshold=0.0).ended is True
            assert turn.run(pcm, threshold=1.0).ended is (r.p >= 1.0)

            # Any chunking of the stream gives the run's scores, bit for bit.
            for chunk in (700, 640, 123, 5000):
                assert _stream(turn, pcm, chunk) == (r.probs, r.speech_probs), chunk

            # flush, reset and run all restart the stream at frame 0.
            assert turn.stream_feed(pcm[:700]).first_frame == 0
            assert turn.stream_feed(pcm[700:1400]).first_frame == 1
            turn.stream_reset()
            assert turn.stream_feed(pcm[:700]).first_frame == 0
            turn.run(pcm)
            assert turn.stream_feed(pcm[:700]).first_frame == 0
            empty = turn.stream_feed(array.array("f"))
            assert empty.probs == () and empty.first_frame == 1


def test_sava_toy_batch_equals_single_feeds(sava_toy_model_path):
    pcms = [_noise(4000, seed=s) for s in (1, 2, 3)]
    with t.Model(sava_toy_model_path, backend="cpu") as model:
        batch = [model.turn_session(n_threads=1) for _ in pcms]
        alone = [model.turn_session(n_threads=1) for _ in pcms]
        try:
            # Different chunk sizes per session, including empty feeds.
            for step in range(8):
                chunks = [p[step * k:(step + 1) * k] for p, k in zip(pcms, (500, 640, 0 if step % 2 else 1300))]
                got = t.TurnSession.stream_feed_batch(list(zip(batch, chunks)))
                want = [s.stream_feed(c) for s, c in zip(alone, chunks)]
                assert got == want, step
            assert [s.stream_flush() for s in batch] == [s.stream_flush() for s in alone]

            # Any iterable of pairs; one result per pair, in order.
            res = t.TurnSession.stream_feed_batch((s, p) for s, p in zip(reversed(batch), pcms))
            assert res == [s.stream_feed(p) for s, p in zip(reversed(alone), pcms)]
        finally:
            for s in batch + alone:
                s.close()


def test_sava_toy_batch_invalid(sava_toy_model_path, vad_toy_model_path):
    pcm = _noise(1000)
    with t.Model(sava_toy_model_path, backend="cpu") as model, \
            t.Model(sava_toy_model_path, backend="cpu") as other:
        a, b, c = model.turn_session(), model.turn_session(), other.turn_session()
        a.stream_feed(pcm[:300])
        with pytest.raises(t.InvalidArgument):
            t.TurnSession.stream_feed_batch([])
        with pytest.raises(t.InvalidArgument, match="repeats"):
            t.TurnSession.stream_feed_batch([(a, pcm), (a, pcm)])
        with pytest.raises(t.InvalidArgument, match="different model"):
            t.TurnSession.stream_feed_batch([(a, pcm), (c, pcm)])
        with pytest.raises(t.InvalidArgument, match="TurnSession"):
            t.TurnSession.stream_feed_batch([(a, pcm), ("b", pcm)])
        with pytest.raises(t.InvalidArgument, match="pair"):
            t.TurnSession.stream_feed_batch([a])
        bad = array.array("f", pcm)
        bad[5] = math.nan
        with pytest.raises(t.InvalidArgument):
            t.TurnSession.stream_feed_batch([(a, pcm), (b, bad)])
        b.close()
        with pytest.raises(t.TranscribeError, match="session is closed"):
            t.TurnSession.stream_feed_batch([(a, pcm), (b, pcm)])
        # Every rejection left a's stream untouched: 300 samples buffered.
        r = a.stream_feed(pcm[300:640])
        assert (len(r.probs), r.first_frame) == (1, 0)


def test_sava_toy_invalid_input(sava_toy_model_path):
    pcm = _noise(2000)
    with t.Model(sava_toy_model_path, backend="cpu") as model:
        with model.turn_session(n_threads=1) as turn:
            for bad in (True, "0.5", [0.5]):
                with pytest.raises(t.InvalidArgument):
                    turn.run(pcm, threshold=bad)  # type: ignore[arg-type]
            for bad in (1.5, math.nan):
                with pytest.raises(t.InvalidArgument):
                    turn.run(pcm, threshold=bad)
            with pytest.raises(t.InvalidArgument):
                turn.run(array.array("f"))
            nan = array.array("f", pcm)
            nan[10] = math.inf
            with pytest.raises(t.InvalidArgument):
                turn.run(nan)

            # Rejected feed input leaves the stream unchanged.
            assert len(turn.stream_feed(pcm[:1000]).probs) == 1  # 360 buffered
            with pytest.raises(t.InvalidArgument):
                turn.stream_feed(nan)
            assert turn.stream_feed(pcm[1000:1280]).first_frame == 1


def test_sava_toy_abort(sava_toy_model_path):
    pcm = _noise(3000)
    with t.Model(sava_toy_model_path, backend="cpu") as model:
        a, b = model.turn_session(n_threads=1), model.turn_session(n_threads=1)
        try:
            with _AlwaysAbort(a):
                with pytest.raises(t.Aborted):
                    a.run(pcm)
            # An abort resets the stream: the next feed starts at frame 0.
            a.stream_feed(pcm[:1300])
            with _AlwaysAbort(a):
                with pytest.raises(t.Aborted):
                    a.stream_feed(pcm[1300:])
            assert a.stream_feed(pcm[:700]).first_frame == 0

            # A batch checks every session's callback and resets every stream.
            b.stream_feed(pcm[:1300])
            with _AlwaysAbort(b):
                with pytest.raises(t.Aborted):
                    t.TurnSession.stream_feed_batch([(a, pcm[:700]), (b, pcm[:700])])
            assert a.stream_feed(pcm[:700]).first_frame == 0
            assert b.stream_feed(pcm[:700]).first_frame == 0
        finally:
            a.close()
            b.close()


def test_turn_results_are_copied_out(sava_toy_model_path):
    pcm = _noise(3000)
    with t.Model(sava_toy_model_path, backend="cpu") as model:
        with model.turn_session(n_threads=1) as turn:
            first = turn.run(pcm)
            kept = (first.probs, first.speech_probs)
            turn.run(_noise(5000, seed=9))
            assert (first.probs, first.speech_probs) == kept
            assert isinstance(first.probs, tuple)
        # Results outlive their session and model.
        assert len(first.probs) == math.ceil(3000 / 640)


# --- real models (env-gated) ----------------------------------------------------


@pytest.mark.parametrize("wav, ended", [
    ("turn-complete-en.wav", True),
    ("turn-incomplete-en.wav", False),
])
def test_smart_turn_real(smart_turn_model_path, wav, ended):
    path = SAMPLES / wav
    if not path.is_file():
        pytest.skip(f"sample not present: {path}")
    with t.Model(smart_turn_model_path, backend="cpu") as model:
        assert model.turn_info.frame_samples == 0
        with model.turn_session() as turn:
            r = turn.run(load_wav(path))
            assert r.ended is ended, r.p


def test_sava_real_stream_and_batch(sava_model_path):
    path = SAMPLES / "sava-speech.wav"
    if not path.is_file():
        pytest.skip(f"sample not present: {path}")
    pcm = load_wav(path)[:16000 * 4]
    with t.Model(sava_model_path, backend="cpu") as model:
        frame = model.turn_info.frame_samples
        assert frame > 0 and model.turn_info.has_speech
        with model.turn_session() as a, model.turn_session() as b:
            r = a.run(pcm)
            assert _stream(a, pcm, 320) == (r.probs, r.speech_probs)
            chunks = [pcm[i:i + 320] for i in range(0, len(pcm), 320)]
            probs: list = []
            for c in chunks:
                ra, rb = t.TurnSession.stream_feed_batch([(a, c), (b, c)])
                assert ra == rb
                probs.extend(ra.probs)
            probs.extend(a.stream_flush().probs)
            assert tuple(probs) == r.probs


def test_ctypes_array_input(sava_toy_model_path):
    pcm = _noise(1280)
    arr = (ctypes.c_float * len(pcm))(*pcm)
    with t.Model(sava_toy_model_path, backend="cpu") as model:
        with model.turn_session(n_threads=1) as turn:
            assert turn.run(arr) == turn.run(pcm)
